  grow: { label: '보완하면 좋음', range: '25~49', tone: 'bg-amber-50 text-amber-700', bar: 'bg-amber-400' },
  focus: { label: '우선 보완', range: '25 미만', tone: 'bg-orange-50 text-orange-700', bar: 'bg-orange-400' },
