export function findTypeMatch(mbtiType: string, discSubtype: string): TypeProfile {
  const primary = discSubtype[0];
  const code = primary + "-" + mbtiType;
  if (typeMatchingMap[code]) return typeMatchingMap[code];
  // fallback: MBTI만으로
  const fb = mbtiFallbackMap[mbtiType];
  if (fb) return { code, ...fb };
  return { code, nameKo: "탐험가", nickname: "Explorer", category: "탐험형", traits: "", careers: "", jobs: "" };
}
