-- HIT - Elevate 전환 준비도 해설 DR-A~D 문안 교체 (2026-10-12, R5)
-- 기존 제목·본문이 '고년차 이직 준비도'(D 맥락) — E는 리더십 전환(내부 승진·이동·어드바이저·독립 포함)이라 다음 역할 전환 기준으로 다시 씀
-- 준비도 = 나의 저니 E 체크리스트(포지셔닝 · 보상 · 레퍼런스·절차) 완료율. 0(체크 전)이면 선택하지 않음 (stage-report-modules)
-- 이전 문안 (롤백용):
--   DR-A '고년차 이직 준비도 — A등급' / 포지셔닝, 연봉 협상, 레퍼런스, 심리적 준비가 모두 높은 수준입니다. 시장에 적극적으로 나설 준비가 완료되었습니다.
--   DR-B '고년차 이직 준비도 — B등급' / 대부분 준비되었으나, 포지셔닝 메시지 정교화나 연봉 협상 전략 등 일부 보완이 필요합니다. 1-2개월 내 시장 진입이 가능합니다.
--   DR-C '고년차 이직 준비도 — C등급' / 이직 의지는 있으나 실질적 준비가 초기 단계입니다. 경력 스토리 재구성, 목표 기업 리서치, 네트워크 활성화 등 3개월 이상의 집중 준비가 필요합니다.
--   DR-D '고년차 이직 준비도 — D등급' / 이직에 대한 막연한 생각 단계입니다. 현재 조직에서의 추가 성장 가능성을 먼저 재점검하고, 이직이 필요하다면 장기 계획을 수립하는 것이 현실적입니다.

UPDATE public.hit_report_modules SET title = v.title, content = v.content, updated_at = now()
FROM (VALUES
 ('DR-A', '리더십 전환 준비 — 출발 준비 완료', '다음 역할로 가기 위한 준비가 탄탄합니다. 왜 지금 이 역할인지 설명할 수 있고, 조건과 절차도 정리되어 있습니다. 이제 기회를 기다리기보다 먼저 만드는 단계입니다 — 원하는 역할을 맡길 사람에게 직접 의사를 전하고, 첫 90일 계획을 미리 그려 두세요.'),
 ('DR-B', '리더십 전환 준비 — 거의 준비됨', '대부분 준비되었고 몇 가지만 다듬으면 됩니다. 내 경력을 다음 역할의 언어로 설명하는 메시지, 그리고 원하는 조건(권한·보상·역할 범위)의 근거를 한 번 더 정리해 보세요. 한두 달 안에 움직일 수 있는 상태입니다.'),
 ('DR-C', '리더십 전환 준비 — 준비 진행 중', '전환하려는 마음은 있지만 실제 준비는 이제 시작 단계입니다. 지금까지의 경력을 "다음 역할에서 무엇을 할 수 있는 사람인가"로 다시 정리하는 것부터 하세요. 나를 추천해 줄 사람을 떠올려 보고, 원하는 역할의 현직자와 대화해 보는 것이 다음 걸음입니다.'),
 ('DR-D', '리더십 전환 준비 — 방향부터 정리', '다음 역할에 대한 준비가 아직 거의 없는 상태입니다. 서두르기보다 방향부터 정리하는 것이 현실적입니다. 지금 조직 안에서 더 클 수 있는 길과 밖으로 나가는 길을 나란히 적어 보고, 어느 쪽이 내 리더십 유형과 맞는지 먼저 점검해 보세요.')
) AS v(id, title, content)
WHERE hit_report_modules.id = v.id;
